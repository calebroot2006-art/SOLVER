"""Match measured turn policies against the pinned reference, or validate the reference alone.

Two modes:

* reference-only (`--reference` without `--project`): validate the capture against the output
  contract in `capture.py` and print its exploitability, iteration count, stop reason and
  runout bookkeeping. It reports `project_capture: absent`, and it is a diagnostic: nothing
  it prints is acceptance of a turn solve, because no project solve was read.
* joint (`--reference` and `--project`, normally with `--review`): the turn gate. Every
  exported public history must match, and every policy row differing by more than two
  percentage points is listed. On top of the structural comparison the joint mode refuses,
  with a named failure rather than a warning:

  - a missing, empty or skipped project capture;
  - a case that did not reach its own target, or stopped for a reason other than reaching
    it, on either side;
  - any difference in the two sides' `input` tables, which carry the case id, board, ranges,
    menus, raise cap, target and starting pot;
  - a project revision that is not a commit, or is not the one `--expected-revision` names;
    the reference's pinned engine and interface revisions are checked by `validate_reference`;
  - a real-gap row with no committed entry, a committed entry for a row that is no longer
    a real gap, or no committed review at all. `review_rule.py` sorts every differing row
    into indifferent, unreached and real gap from the numbers both captures measured, so
    the first two categories are recomputed here rather than read out of a file;
  - a case whose real-gap rows cost more, reach-weighted, than the rule's budget;
  - a committed review generated under a different rule than the one in force;
  - a stale review: an entry whose recorded row values are no longer the captured ones, or
    which records no values at all and so cannot be checked against this capture.
"""

